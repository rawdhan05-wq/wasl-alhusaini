const CLUB_LOGO_MAP = (() => {
  const map = {};
  const keyOf = (value) => String(value ?? "")
    .toLowerCase()
    .replace(/[\u064B-\u065F\u0670]/g, "")
    .replace(/[أإآٱ]/g, "ا")
    .replace(/ى/g, "ي")
    .replace(/ؤ/g, "و")
    .replace(/ئ/g, "ي")
    .replace(/ة/g, "ه")
    .replace(/[ـ]/g, "")
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/&/g, " and ")
    .replace(/\b(fc|afc|cf|sc|ac|as|ss|ssc|bc|cfc|ud|rcd|rc|sv|vfb|tsg|osc|sco|aj|es|ogc|us|acf|calcio|club|de|of)\b/g, " ")
    .replace(/\b(18|19|20)\d{2}\b/g, " ")
    .replace(/\b0\d\b/g, " ")
    .replace(/[^a-z0-9\u0600-\u06FF]+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  const add = (slug, name) => {
    const key = keyOf(name);
    if (key) map[key] = `${CLUB_LOGO_BASE}${slug}.png`;
  };
  Object.entries(CLUB_LOGO_AR).forEach(([slug, arabic]) => {
    add(slug, slug.replace(/-/g, " "));
    add(slug, arabic);
    (CLUB_LOGO_EXTRA[slug] || []).forEach((name) => add(slug, name));
  });
  return map;
})();

